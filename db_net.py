def resize_and_blockify(img_path, mask_path, out_img_path, out_lbl_path):
    # Read files
    img = cv2.imread(img_path, cv2.IMREAD_COLOR)
    mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)
    if img is None or mask is None:
        print("Missing file:", img_path, mask_path)
        return

    # Resize image and mask
    img = cv2.resize(img, (TARGET_W, TARGET_H), interpolation=cv2.INTER_LINEAR)
    mask = cv2.resize(mask, (TARGET_W, TARGET_H), interpolation=cv2.INTER_NEAREST)

    # Convert to block labels
    block_h, block_w = TARGET_H // GRID_H, TARGET_W // GRID_W
    block_labels = np.zeros((GRID_H, GRID_W), dtype=np.uint8)
    for gy in range(GRID_H):
        for gx in range(GRID_W):
            x0, x1 = gx * block_w, (gx + 1) * block_w
            y0, y1 = gy * block_h, (gy + 1) * block_h
            block = mask[y0:y1, x0:x1]
            smoke_fraction = np.count_nonzero(block) / (block_w * block_h)
            block_labels[gy, gx] = 1 if smoke_fraction >= THRESHOLD else 0

    # Save resized image and block label
    cv2.imwrite(out_img_path, img)
    np.save(out_lbl_path, block_labels)

