import torch
import torch.nn as nn
import torch.optim as optim
import numpy as np
from tqdm import tqdm
import os

device = 'cuda' if torch.cuda.is_available() else 'cpu'
model = DBNet(num_classes=2, pretrained=True).to(device)

# ---- Optional class weights (adjust after checking data imbalance) ----
class_weights = torch.tensor([1.0, 5.0]).to(device)
criterion = nn.CrossEntropyLoss(weight=class_weights)

optimizer = optim.Adam(model.parameters(), lr=1e-4, weight_decay=1e-5)
scheduler = optim.lr_scheduler.StepLR(optimizer, step_size=10, gamma=0.5)

# ---------------------------
# Helper: IoU computation
# ---------------------------
def compute_iou(pred, target, num_classes=2):
    ious = []
    for cls in range(num_classes):
        pred_inds = (pred == cls)
        target_inds = (target == cls)
        intersection = (pred_inds & target_inds).sum()
        union = (pred_inds | target_inds).sum()
        if union == 0:
            ious.append(float('nan'))
        else:
            ious.append(intersection / union)
    return ious

def evaluate(model, loader, criterion, device):
    model.eval()
    total_loss = 0
    iou_scores = []
    with torch.no_grad():
        for imgs, labels in tqdm(loader, desc="Validating", leave=False):
            imgs, labels = imgs.to(device), labels.to(device)
            logits = model(imgs)
            loss = criterion(logits, labels)
            total_loss += loss.item() * imgs.size(0)

            preds = torch.argmax(logits, dim=1).cpu().numpy()
            targets = labels.cpu().numpy()
            for p, t in zip(preds, targets):
                ious = compute_iou(p, t)
                iou_scores.append(ious)
    avg_loss = total_loss / len(loader.dataset)
    avg_ious = np.nanmean(iou_scores, axis=0)
    return avg_loss, avg_ious

