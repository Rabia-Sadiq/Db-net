# --- Normalization for RGB images (ImageNet stats are a good default) ---
normalize = transforms.Normalize(mean=[0.485, 0.456, 0.406],
                                 std=[0.229, 0.224, 0.225])

class SmokeDataset(Dataset):
    def __init__(self, img_dir, lbl_dir, augment=False):
        self.img_files = sorted(os.listdir(img_dir))
        self.lbl_files = sorted(os.listdir(lbl_dir))
        self.img_dir = img_dir
        self.lbl_dir = lbl_dir
        self.augment = augment

        self.to_tensor_norm = transforms.Compose([
            transforms.ToTensor(),  # H,W,C → C,H,W and 0..1 scaling
            normalize
        ])
        self.color = transforms.ColorJitter(0.1, 0.1, 0.1, 0.05) if augment else None

    def __len__(self):
        return len(self.img_files)

    def __getitem__(self, idx):
        # --- Load image ---
        img_path = os.path.join(self.img_dir, self.img_files[idx])
        img_bgr = cv2.imread(img_path, cv2.IMREAD_COLOR)
        img = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)  # shape H×W×3

        # --- Load label ---
        lbl_path = os.path.join(self.lbl_dir, self.lbl_files[idx])
        target = np.load(lbl_path).astype(np.int64)  # shape 34×60, values 0/1

        # --- Convert to tensor ---
        img = self.to_tensor_norm(img)               # shape 3×540×960
        target = torch.from_numpy(target)            # shape 34×60

        # --- Augmentation ---
        if self.augment:
            # Color jitter (image only)
            img = self.color(img)

            # Horizontal flip (image + label together)
            if torch.rand(1).item() < 0.5:
                img = torch.flip(img, dims=[2])       # flip width of image [C,H,W]
                target = torch.flip(target, dims=[1]) # flip width of grid [H_grid,W_grid]

        return img, target

