import torch
import torch.nn as nn
import torch.nn.functional as F
from torchvision.models import resnet50

# ----------------------------
# DB-Net model
# ----------------------------
class DBNet(nn.Module):
    """
    DB-Net as described in the paper (dual-branch, block-wise prediction).
    - Uses ResNet-50 backbone up to layer3 (so final encoder stride = 16).
    - Projects selected feature taps to `num_classes` channels with 1x1 conv.
    - Downsamples shallower taps to the deepest tap resolution, sums, and
      optionally refines with a small head.
    - Returns logits with shape [B, num_classes, H_out, W_out], where H_out,W_out
      depend on the backbone output spatial resolution (usually input/16).
    """
    def __init__(self, num_classes=2, pretrained=True, refine=True):
        super(DBNet, self).__init__()
        backbone = resnet50(weights='IMAGENET1K_V1' if pretrained else None)

        # Stem: conv1 + bn1 + relu + maxpool
        self.stem = nn.Sequential(
            backbone.conv1, backbone.bn1, backbone.relu, backbone.maxpool
        )  # After stem -> stride 4 of original input

        # ResNet stages (we take layer1..layer3)
        self.layer1 = backbone.layer1  # typically output channels = 256 (stride 4)
        self.layer2 = backbone.layer2  # output channels = 512 (stride 8)
        self.layer3 = backbone.layer3  # output channels = 1024 (stride 16)

        # Project each tapped feature to num_classes via 1x1 conv
        # (paper used 2 output channels for block-wise binary classification)
        self.proj1 = nn.Conv2d(256, num_classes, kernel_size=1)   # from layer1
        self.proj2 = nn.Conv2d(512, num_classes, kernel_size=1)   # from layer2
        self.proj3 = nn.Conv2d(1024, num_classes, kernel_size=1)  # from layer3

        # Optional small refinement head (stabilize / smooth the summed map)
        self.refine = refine
        if self.refine:
            self.head = nn.Sequential(
                nn.Conv2d(num_classes, num_classes, kernel_size=3, padding=1, bias=False),
                nn.BatchNorm2d(num_classes),
                nn.ReLU(inplace=True),
                nn.Conv2d(num_classes, num_classes, kernel_size=1)
            )
        else:
            self.head = nn.Identity()

        # initialization: small proj and head are initialized by default; you can refine if needed

    def forward(self, x):
        """
        x: [B, 3, H, W] (e.g., [B,3,540,960])
        returns: logits [B, num_classes, H_out, W_out]
        typically H_out = H/16, W_out = W/16 (but depends on exact input / padding)
        """

        # --- Encoder / Main branch ---
        s = self.stem(x)       # after conv1+maxpool -> stride 4
        f1 = self.layer1(s)    # /4 spatial, channels=256
        f2 = self.layer2(f1)   # /8 spatial, channels=512
        f3 = self.layer3(f2)   # /16 spatial, channels=1024  <-- deepest tap

        # --- Project each tap to num_classes channels ---
        p1 = self.proj1(f1)  # [B, num_classes, H1, W1]  (H1 ~ H/4)
        p2 = self.proj2(f2)  # [B, num_classes, H2, W2]  (H2 ~ H/8)
        p3 = self.proj3(f3)  # [B, num_classes, H3, W3]  (H3 ~ H/16)

        # --- Downsample p1, p2 to p3's spatial resolution and sum ---
        target_size = p3.shape[2:],  # (H3, W3)
        H3, W3 = p3.shape[2], p3.shape[3]

        # Use bilinear up/down sampling to align spatial sizes
        p1_ds = F.interpolate(p1, size=(H3, W3), mode='bilinear', align_corners=False)
        p2_ds = F.interpolate(p2, size=(H3, W3), mode='bilinear', align_corners=False)

        agg = p1_ds + p2_ds + p3  # elementwise sum --> [B, num_classes, H3, W3]

        # Optional refinement head (small conv block)
        out = self.head(agg)  # logits, not normalized

        # Important: DO NOT apply softmax here if you use CrossEntropyLoss. Return raw logits.
        return out


