if os.path.exists(ckpt_path):
    checkpoint = torch.load(ckpt_path)
    model.load_state_dict(checkpoint['model_state_dict'])
    optimizer.load_state_dict(checkpoint['optimizer_state_dict'])
    scheduler.load_state_dict(checkpoint['scheduler_state_dict'])
    start_epoch = checkpoint['epoch'] + 1
    best_val_iou = checkpoint['best_val_iou']
    print(f"Resuming training from epoch {start_epoch}, best IoU {best_val_iou:.4f}")

# ---- CSV log ----
log_path = os.path.join(save_dir, "training_log.csv")
log_file = open(log_path, "a" if start_epoch > 1 else "w")
if start_epoch == 1:
    log_file.write("epoch,train_loss,val_loss,val_iou_bg,val_iou_smoke\n")

for epoch in range(start_epoch, num_epochs+1):
    model.train()
    train_loss = 0.0

    for imgs, labels in tqdm(train_loader, desc=f"Epoch {epoch}/{num_epochs}"):
        imgs, labels = imgs.to(device), labels.to(device)
        optimizer.zero_grad()
        logits = model(imgs)
        loss = criterion(logits, labels)
        loss.backward()
        optimizer.step()
        train_loss += loss.item() * imgs.size(0)

    train_loss /= len(train_loader.dataset)
    val_loss, val_ious = evaluate(model, val_loader, criterion, device)
    val_iou_bg, val_iou_smoke = val_ious

    # ---- Write log ----
    log_file.write(f"{epoch},{train_loss:.4f},{val_loss:.4f},{val_iou_bg:.4f},{val_iou_smoke:.4f}\n")
    log_file.flush()

    print(f"Epoch {epoch} - "
          f"Train Loss: {train_loss:.4f}, "
          f"Val Loss: {val_loss:.4f}, "
          f"IoU BG: {val_iou_bg:.4f}, IoU Smoke: {val_iou_smoke:.4f}")

    # ---- Save best model ----
    mean_val_iou = np.nanmean(val_ious)
    if mean_val_iou > best_val_iou:
        best_val_iou = mean_val_iou
        torch.save(model.state_dict(), os.path.join(save_dir, "dbnet_best.pth"))
        print(">>> Saved best model (IoU improved).")

    # ---- Always save checkpoint ----
    torch.save({
        'epoch': epoch,
        'model_state_dict': model.state_dict(),
        'optimizer_state_dict': optimizer.state_dict(),
        'scheduler_state_dict': scheduler.state_dict(),
        'best_val_iou': best_val_iou
    }, ckpt_path)

    scheduler.step()

log_file.close()
print("Training finished. Best IoU:", best_val_iou)

